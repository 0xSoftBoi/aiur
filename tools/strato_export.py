"""Export sized STRATO design points to the formats other tools consume.

For each design in the ladder this writes

* ``hardware/strato/design-points/<name>.json`` - the full sized budget;
* ``ros2_ws/src/aiur_description/urdf/<name>.urdf`` - frames per REP-103/105
  (``base_link`` at the centre of volume, x forward, y left, z up);
* ``ros2_ws/src/aiur_description/meshes/<name>_hull.stl`` - the hull loft;
* ``ros2_ws/src/aiur_description/models/<name>/model.sdf`` and a
  ``worlds/<name>_float.sdf`` - a Gazebo model at float density using the
  stock Buoyancy and LighterThanAirDynamics systems, as an independent check
  on the in-repo 6-DoF model.

Everything is generated; do not hand-edit the outputs.

    python tools/strato_export.py
"""

from __future__ import annotations

import json
import math
import os
import struct
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from aiur.strato.atmosphere import isa  # noqa: E402
from aiur.strato.flight6dof import Airframe  # noqa: E402
from aiur.strato.hull import Hull, profile  # noqa: E402
from aiur.strato.sizing import ladder  # noqa: E402

DESC = os.path.join(REPO, "ros2_ws", "src", "aiur_description")


def slug(key: str) -> str:
    return key.replace("/", "_")


def write_hull_stl(path: str, hull: Hull, x_cv: float, stations: int = 48, seg: int = 28) -> None:
    """Binary STL of the hull in base_link axes (origin at centre of volume)."""

    rings = []
    for i in range(stations + 1):
        xi = i / stations
        r = hull.radius_m * profile(min(max(xi, 1e-4), 1 - 1e-4))
        x = x_cv - xi * hull.length_m          # nose at +x
        rings.append([(x, r * math.cos(2 * math.pi * j / seg), r * math.sin(2 * math.pi * j / seg))
                      for j in range(seg)])
    tris = []
    for i in range(stations):
        for j in range(seg):
            a, b = rings[i][j], rings[i][(j + 1) % seg]
            c, d = rings[i + 1][j], rings[i + 1][(j + 1) % seg]
            tris.append((a, c, b))
            tris.append((b, c, d))
    with open(path, "wb") as fh:
        fh.write(b"aiur strato hull".ljust(80, b" "))
        fh.write(struct.pack("<I", len(tris)))
        for a, b, c in tris:
            u = [b[k] - a[k] for k in range(3)]
            v = [c[k] - a[k] for k in range(3)]
            n = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
            m = math.sqrt(sum(k * k for k in n)) or 1.0
            fh.write(struct.pack("<12fH", *(k / m for k in n), *a, *b, *c, 0))


def urdf(key: str, dp, af: Airframe) -> str:
    h = af.hull
    name = slug(key)
    length, r = h.length_m, h.radius_m
    xcv = af.x_cv
    fin_area = dp.geometry["fin_area_total_m2"] / 4.0
    fin_chord = math.sqrt(fin_area * 1.6)
    fin_span = fin_area / fin_chord
    x_fin = xcv - 0.86 * length
    x_stern = xcv - length
    ixx, iyy, izz = af.inertia
    below = -(r + 0.25)
    fins = ""
    for i, roll in enumerate((45, 135, 225, 315)):
        rr = math.radians(roll)
        rad = h.radius_at(0.86 * length) + fin_span / 2
        fins += f'''
  <link name="fin_{i}_link"><visual><geometry><box size="{fin_chord:.3f} 0.04 {fin_span:.3f}"/></geometry>
    <material name="fin"><color rgba="0.85 0.85 0.9 0.9"/></material></visual></link>
  <joint name="fin_{i}_joint" type="fixed"><parent link="base_link"/><child link="fin_{i}_link"/>
    <origin xyz="{x_fin:.3f} {-rad*math.sin(rr):.3f} {rad*math.cos(rr):.3f}" rpy="{rr:.4f} 0 0"/></joint>'''

    def fixed(child, xyz, size=None, color="0.2 0.2 0.2 1"):
        vis = (f'<visual><geometry><box size="{size}"/></geometry>'
               f'<material name="{child}"><color rgba="{color}"/></material></visual>') if size else ""
        return f'''
  <link name="{child}">{vis}</link>
  <joint name="{child}_joint" type="fixed"><parent link="base_link"/><child link="{child}"/>
    <origin xyz="{xyz}" rpy="0 0 0"/></joint>'''

    return f'''<?xml version="1.0"?>
<!-- GENERATED by tools/strato_export.py from design point {key}. Do not edit. -->
<robot name="aiur_{name}">
  <link name="base_link">
    <inertial><mass value="{af.mass_kg:.4f}"/>
      <origin xyz="0 0 {-af.cg_below_cv_m:.4f}"/>
      <inertia ixx="{ixx:.3f}" iyy="{iyy:.3f}" izz="{izz:.3f}" ixy="0" ixz="0" iyz="0"/></inertial>
    <visual><geometry><mesh filename="package://aiur_description/meshes/{name}_hull.stl"/></geometry>
      <material name="film"><color rgba="0.92 0.94 0.97 0.55"/></material></visual>
  </link>{fins}{fixed("bay_link", f"0 0 {below:.3f}", "0.26 0.16 0.12", "0.95 0.6 0.1 1")}{fixed("payload_link", f"{0.28*length:.3f} 0 {below:.3f}", "0.20 0.14 0.12", "0.2 0.5 0.9 1")}{fixed("ftu_link", f"{-0.5:.3f} 0 {below:.3f}", "0.10 0.07 0.05", "0.9 0.1 0.1 1")}{fixed("gnss_link", f"0 0 {below+0.10:.3f}")}{fixed("baro_link", f"0 0 {below:.3f}")}{fixed("ambient_probe", f"0.4 0 {below-0.2:.3f}")}{fixed("gas_probe", f"0 0 {-r+0.3:.3f}")}
  <link name="stern_pod_link"><visual><geometry><box size="0.22 0.10 0.10"/></geometry>
    <material name="pod"><color rgba="0.15 0.15 0.15 1"/></material></visual></link>
  <joint name="stern_pod_joint" type="fixed"><parent link="base_link"/><child link="stern_pod_link"/>
    <origin xyz="{x_stern - 0.15:.3f} 0 0"/></joint>
  <link name="gimbal_yaw_link"/>
  <joint name="gimbal_yaw_joint" type="revolute"><parent link="stern_pod_link"/><child link="gimbal_yaw_link"/>
    <origin xyz="-0.12 0 0"/><axis xyz="0 0 1"/>
    <limit lower="-0.436" upper="0.436" effort="1.0" velocity="1.05"/></joint>
  <link name="gimbal_pitch_link"/>
  <joint name="gimbal_pitch_joint" type="revolute"><parent link="gimbal_yaw_link"/><child link="gimbal_pitch_link"/>
    <axis xyz="0 1 0"/><limit lower="-0.436" upper="0.436" effort="1.0" velocity="1.05"/></joint>
  <link name="propeller_link"><visual><geometry>
    <cylinder radius="{dp.propulsion['prop_diameter_m']/2:.3f}" length="0.01"/></geometry>
    <origin rpy="0 1.5708 0"/><material name="prop"><color rgba="0.1 0.1 0.1 0.5"/></material></visual></link>
  <joint name="propeller_joint" type="continuous"><parent link="gimbal_pitch_link"/><child link="propeller_link"/>
    <origin xyz="-0.08 0 0"/><axis xyz="1 0 0"/></joint>
</robot>
'''


def sdf(key: str, dp, af: Airframe, thrust_n: float, rail: bool = False) -> tuple[str, str]:
    h = af.hull
    name = slug(key) + ("_rail" if rail else "")
    air = af.air
    a = h.length_m / 2.0
    b = math.sqrt(h.volume_m3 / (4.0 / 3.0 * math.pi * a))   # ellipsoid of equal volume
    ixx, iyy, izz = af.inertia
    re = air.density_kg_m3 * dp.mission["cruise_airspeed_m_s"] * h.length_m / air.viscosity_pa_s
    axial = h.drag_coefficient(re) * af.drag_multiplier * h.reference_area_m2
    k1, k2, _ = h.lamb_factors()
    # Li & Nahon hull integrals, with flow separation at 0.4 L aft of the nose.
    eps = 0.4 * h.length_m
    i1 = math.pi * h.radius_at(eps) ** 2
    j1 = sum(2 * rad * dx for x, rad, dx in h.stations(60) if x >= eps)
    i3 = sum((math.pi * (h.radius_at(x + dx / 2) ** 2 - h.radius_at(x - dx / 2) ** 2))
             * (af.x_cv - x) for x, rad, dx in h.stations(200) if x <= eps)
    j2 = sum(2 * rad * dx * (x - af.x_cv) for x, rad, dx in h.stations(60) if x >= eps)
    # The stock plugin models the bare hull: no fins.  A finless hull is
    # Munk-unstable and tumbles, so the axial-drag comparison runs on a rail.
    rail_joint = ('    <joint name="rail" type="prismatic"><parent>world</parent><child>base_link</child>'
                  '<axis><xyz>1 0 0</xyz></axis></joint>\n') if rail else ""
    model = f'''<?xml version="1.0"?>
<!-- GENERATED by tools/strato_export.py from design point {key}. Do not edit. -->
<sdf version="1.9">
  <model name="aiur_{name}">
    <link name="base_link">
      <inertial>
        <pose>0 0 {-af.cg_below_cv_m:.4f} 0 0 0</pose>
        <mass>{af.m_disp:.5f}</mass>
        <inertia><ixx>{ixx:.3f}</ixx><iyy>{iyy:.3f}</iyy><izz>{izz:.3f}</izz>
          <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
        <fluid_added_mass>
          <xx>{af.a11[0]:.5f}</xx><yy>{af.a11[1]:.5f}</yy><zz>{af.a11[2]:.5f}</zz>
          <pp>0</pp><qq>{af.a22[1]:.4f}</qq><rr>{af.a22[2]:.4f}</rr>
        </fluid_added_mass>
      </inertial>
      <collision name="hull"><geometry><ellipsoid><radii>{a:.4f} {b:.4f} {b:.4f}</radii></ellipsoid></geometry></collision>
      <visual name="hull"><geometry><ellipsoid><radii>{a:.4f} {b:.4f} {b:.4f}</radii></ellipsoid></geometry></visual>
    </link>
    <plugin filename="gz-sim-lighter_than_air_dynamics-system" name="gz::sim::systems::LighterThanAirDynamics">
      <air_density>{air.density_kg_m3:.5f}</air_density>
      <link_name>base_link</link_name>
      <force_inviscid_coeff>{-(k2-k1)*i1:.4f}</force_inviscid_coeff>
      <force_viscous_coeff>{af.crossflow_cd*j1:.4f}</force_viscous_coeff>
      <moment_inviscid_coeff>{(k2-k1)*i3:.4f}</moment_inviscid_coeff>
      <moment_viscous_coeff>{af.crossflow_cd*j2:.4f}</moment_viscous_coeff>
      <eps_v>{eps - af.x_cv:.4f}</eps_v>
      <axial_drag_coeff>{axial:.5f}</axial_drag_coeff>
    </plugin>
    <plugin filename="gz-sim-odometry-publisher-system" name="gz::sim::systems::OdometryPublisher">
      <odom_frame>map</odom_frame><robot_base_frame>base_link</robot_base_frame>
      <odom_publish_frequency>10</odom_publish_frequency><dimensions>3</dimensions>
      <odom_topic>/model/aiur/odometry</odom_topic>
    </plugin>
{rail_joint}  </model>
</sdf>
'''
    world = f'''<?xml version="1.0"?>
<!-- GENERATED by tools/strato_export.py. Air at {dp.mission["float_altitude_m"]/1000:g} km. -->
<sdf version="1.9">
  <world name="strato">
    <physics name="10ms" type="ignored"><max_step_size>0.01</max_step_size><real_time_factor>0</real_time_factor></physics>
    <gravity>0 0 -9.80665</gravity>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-buoyancy-system" name="gz::sim::systems::Buoyancy">
      <uniform_fluid_density>{air.density_kg_m3:.5f}</uniform_fluid_density>
    </plugin>
    <plugin filename="gz-sim-apply-link-wrench-system" name="gz::sim::systems::ApplyLinkWrench">
      <persistent><entity_name>aiur_{name}::base_link</entity_name><entity_type>link</entity_type>
        <force>{thrust_n:.4f} 0 0</force><torque>0 0 0</torque></persistent>
    </plugin>
    <include><uri>model://{name}</uri><pose>0 0 100 0 0 0</pose></include>
  </world>
</sdf>
'''
    return model, world


def main() -> int:
    pts = ladder()
    os.makedirs(os.path.join(REPO, "hardware", "strato", "design-points"), exist_ok=True)
    for sub in ("urdf", "meshes", "models", "worlds"):
        os.makedirs(os.path.join(DESC, sub), exist_ok=True)
    index = {}
    for key, dp in pts.items():
        name = slug(key)
        with open(os.path.join(REPO, "hardware", "strato", "design-points", name + ".json"), "w") as fh:
            fh.write(dp.to_json() + "\n")
        if dp.architecture != "hull" or not key.startswith(("S1", "S2")):
            continue
        af = Airframe.from_design(dp)
        write_hull_stl(os.path.join(DESC, "meshes", name + "_hull.stl"), af.hull, af.x_cv)
        with open(os.path.join(DESC, "urdf", name + ".urdf"), "w") as fh:
            fh.write(urdf(key, dp, af))
        thrust = dp.propulsion["drag_cruise_n"]
        for rail in (False, True):
            model, world = sdf(key, dp, af, thrust, rail)
            mname = name + ("_rail" if rail else "")
            os.makedirs(os.path.join(DESC, "models", mname), exist_ok=True)
            with open(os.path.join(DESC, "models", mname, "model.sdf"), "w") as fh:
                fh.write(model)
            with open(os.path.join(DESC, "models", mname, "model.config"), "w") as fh:
                fh.write(f'<?xml version="1.0"?>\n<model><name>{mname}</name><version>1.0</version>'
                         f'<sdf version="1.9">model.sdf</sdf><description>Generated from design '
                         f'point {key}</description></model>\n')
            with open(os.path.join(DESC, "worlds", mname + ("" if rail else "_float") + ".sdf"), "w") as fh:
                fh.write(world)
        index[key] = {"cruise_thrust_n": thrust, "expected_airspeed_m_s": dp.mission["cruise_airspeed_m_s"],
                      "mass_kg": af.m_disp, "added_mass_x_kg": af.a11[0]}
        print(f"exported {key}: {af.hull.length_m:.1f} m hull, {af.mass_kg:.2f} kg")
    with open(os.path.join(DESC, "worlds", "expectations.json"), "w") as fh:
        json.dump(index, fh, indent=2)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
