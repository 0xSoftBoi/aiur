"""Export sized STRATO design points to the formats other tools consume.

For each design in the ladder this writes

* ``hardware/strato/design-points/<name>.json`` - the full sized budget;
* ``ros2_ws/src/aiur_description/urdf/<name>.urdf`` - frames per REP-103/105
  (``base_link`` at the centre of volume, x forward, y left, z up);
* ``ros2_ws/src/aiur_description/meshes/<name>_hull.stl`` - the hull loft;
* ``ros2_ws/src/aiur_description/models/<name>/model.sdf`` and a
  ``worlds/<name>_float.sdf`` - a Gazebo model at float density using the
  stock Buoyancy and LighterThanAirDynamics systems, as an independent check
  on the in-repo 6-DoF model.

Everything is generated; do not hand-edit the outputs.

    python tools/strato_export.py
"""

